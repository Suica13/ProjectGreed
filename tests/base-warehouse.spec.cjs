 await page.locator('#warehouseDialog input[type=search]').fill('Type61');
 const row=page.locator('.warehouse-production-row[data-unit-id=Type61]');
 await expect(row.locator('button')).toBeEnabled();
 await row.locator('button').click();
 await expect(page.locator('#warehouseDialog')).not.toBeVisible();
 expect(await page.evaluate(()=>Economy.snapshot().storage.units[0].slot)).toBe(5);
 await expect(page.locator('.warehouse-bay[data-slot="5"] canvas')).toHaveAttribute('data-preview-angle','180');

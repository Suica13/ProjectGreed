const {test,expect}=require('@playwright/test');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
for(const width of [1600,390]) test('fixed era and custom battlefield settings at '+width,async({page})=>{
  test.setTimeout(60000);
  await page.setViewportSize({width,height:width===390?844:1000});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.resolve('public/client.html')).href);
  await expect(page.locator('#openSkirmish')).toBeEnabled();
  await page.locator('#openSkirmish').click();
  await page.locator('#offlineRoomMode').selectOption('battlefield');
  await page.locator('#createOfflineRoom').click();
  if(width===390)await page.getByRole('button',{name:'房间设置',exact:true}).click();
  await expect(page.locator('#battlefieldEra')).toHaveValue('custom');
  for(const era of ['0079T1','0079T2','0087T1','0087T2']){
    await page.locator('#battlefieldEra').selectOption(era);
    await expect.poll(()=>page.evaluate(()=>Net.snapshot.settings.battlefieldEra)).toBe(era);
    await expect(page.locator('#battlefieldCustomScale')).toBeHidden();
    await expect(page.locator('#roomCostLimit')).toBeHidden();
    expect(await page.locator('#battlefieldTeam0era').count()).toBe(0);
    expect(await page.locator('#battlefieldTeam1era').count()).toBe(0);
    expect(await page.locator('#battlefieldScalePreset option').count()).toBe(5);
    const factions=await page.locator('#battlefieldTeam0faction option').evaluateAll(o=>o.map(v=>v.value));
    expect(factions).toEqual(era.startsWith('0079')?['EFSF','ZEON']:['AEUG','TITANS','NEO_ZEON']);
    await page.locator('#battlefieldScalePreset').selectOption(era+'-war');
    await expect.poll(()=>page.evaluate(()=>Rules.battlefieldMode.roomPreset(Net.snapshot.settings)?.id)).toBe(era+'-war');
  }
  await page.locator('#battlefieldTeam0faction').selectOption('NEO_ZEON');
  await expect.poll(()=>page.evaluate(()=>Net.snapshot.settings.battlefieldTeams[0].faction)).toBe('NEO_ZEON');
  await page.locator('#battlefieldEra').selectOption('custom');
  await expect(page.locator('#battlefieldCustomScale')).toBeVisible();
  await expect(page.locator('#battlefieldTeam0era')).toBeVisible();
  await expect(page.locator('#roomCostLimit')).toBeVisible();
  expect(await page.locator('#battlefieldScalePreset option').count()).toBe(21);
  await page.locator('#roomCostLimit').fill('99999');
  await page.locator('#roomCostLimit').blur();
  await expect.poll(()=>page.evaluate(()=>Net.snapshot.settings.costLimit)).toBe(99999);
  await page.locator('#battlefieldTeam1faction').selectOption('EFSF');
  await expect.poll(()=>page.evaluate(()=>Net.snapshot.settings.battlefieldTeams[1].era)).toBe('0079T1');
  await expect(page.locator('#battlefieldEntryReward')).toHaveText('阵营AI每5回合空投增援 · 单位阵亡扣除库存 · 击坠与助攻给予奖励');
  expect(await page.evaluate(()=>[0,1].map(team=>Rules.battlefieldMode.baseReward(Net.snapshot.settings,team).money))).toEqual([11718,6000]);
  const order=await page.locator('.room-battle-rules > label select, .room-battle-rules > details').evaluateAll(els=>els.map(el=>el.id));
  expect(order).toEqual(['roomBattleMode','roomFogMode','roomShareAlliedUnits','roomPilotPolicy','roomPilotDialogue','roomClimateOptions']);
  expect(await page.locator('#roomSettingsPage').evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true);
  await page.locator('#battlefieldEra').scrollIntoViewIfNeeded();
  await page.screenshot({path:`tmp/verification/screenshots/battlefield-era-settings-${width}.png`});
  await page.locator('#roomBattleMode').selectOption('regular');
  await expect.poll(()=>page.evaluate(()=>Net.snapshot.settings.mode)).toBe('regular');
  await expect(page.locator('#roomFormationRules')).toBeVisible();
  expect(await page.locator('#roomCostLimit').evaluate(el=>el.closest('details').id)).toBe('roomFormationRules');
  expect(errors).toEqual([]);
});

const {test,expect}=require("@playwright/test");
const {pathToFileURL}=require("node:url"),path=require("node:path");
for(const width of [1440,390]) test(`regional side tabs and expanded movement flow at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:900});
  const errors=[];page.on("pageerror",e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.resolve("public/client.html")).href);
  await expect(page.locator("#openSkirmish")).toBeEnabled();
  await page.evaluate(()=>{const factory=createRoomEngine;createRoomEngine=options=>(window.testEngine=factory(options));});
  await page.locator("#openSkirmish").click();await page.locator("#offlineRoomMode").selectOption("campaign");
  await page.locator("#createOfflineRoom").click();await page.locator("#startRoomGame").click();
  await page.locator(".campaign-setup button").last().click();
  await expect(page.locator("#campaignScreen")).toBeVisible();
  await expect.poll(()=>page.evaluate(()=>Net.awaiting)).toBe(null);
  await page.evaluate(()=>{
    const room=[...testEngine.rooms.values()][0],s=room.campaign,ctx={G:Rules,production:PRODUCTION_CATALOG};
    s.units=[];window.friendlyArmy=CampaignRules.addUnit(ctx,s,0,"jaburo","Type61").id;
    window.enemyArmy=CampaignRules.addUnit(ctx,s,1,"jaburo","MS_06F").id;
    s.teams[0].intelligence.progress=100;
    room.revision++;testEngine.broadcast(room);
  });
  const sidebar=page.locator(".campaign-detail");
  await expect(sidebar.locator(".campaign-force-card")).toHaveCount(1);
  await expect(sidebar.locator(".campaign-force-card")).toHaveAttribute("data-unit-id",await page.evaluate(()=>friendlyArmy));
  await sidebar.locator('[data-force-side="enemy"]').click();
  await expect(sidebar.locator(".campaign-force-card")).toHaveAttribute("data-unit-id",await page.evaluate(()=>enemyArmy));
  await expect(sidebar.locator('.campaign-force-card input')).toBeDisabled();
  await sidebar.locator(".campaign-forces-expand").click();
  const dialog=page.locator("#campaignForceDetailsDialog");await expect(dialog).toBeVisible();
  await dialog.locator('[data-force-side="friendly"]').click();
  await expect(dialog.locator('.campaign-force-card input')).toBeEnabled();
  await dialog.locator('.campaign-force-card input').check();
  await dialog.getByRole("button",{name:"调动",exact:true}).click();
  await expect(dialog).not.toBeVisible();await expect(page.locator("#campaignMoveDock")).toBeVisible();
  await page.locator('[data-destination="andes"]').click();
  await page.locator("#campaignConfirmMove").click();
  await expect(dialog).toBeVisible();
  await expect.poll(()=>page.evaluate(()=>Net.snapshot.campaign.units.find(u=>u.id===friendlyArmy).moveTo)).toBe("andes");
  await dialog.getByRole("button",{name:"调动",exact:true}).click();
  await expect(dialog).not.toBeVisible();
  await page.locator("#campaignMoveDock").getByRole("button",{name:"取消",exact:true}).click();
  await expect(dialog).toBeVisible();
  const bounds=await dialog.boundingBox();expect(bounds.x).toBeGreaterThanOrEqual(0);expect(bounds.x+bounds.width).toBeLessThanOrEqual(width+1);
  await dialog.getByRole("button",{name:"关闭",exact:true}).click();
  const geometry=await page.evaluate(()=>{
    const scroll=document.querySelector('.campaign-map-scroll'),svg=scroll.querySelector('svg');
    const fitted=Math.min(scroll.clientWidth,scroll.clientHeight*1200/560);
    const box=svg.querySelector('.campaign-region-label-box');
    return {width:svg.getBoundingClientRect().width,fitted,boxWidth:box.getBoundingClientRect().width};
  });
  expect(geometry.width/geometry.fitted).toBeCloseTo(1.25*1.25,2);
  expect(geometry.boxWidth).toBeCloseTo(116*geometry.fitted*1.25/1200,0);
  expect(errors).toEqual([]);
});

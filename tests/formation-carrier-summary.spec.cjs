const {test,expect}=require('@playwright/test');
const {pathToFileURL}=require('node:url');
const path=require('node:path');

for(const width of [1440,390]) test(`carrier summary and secondary loading page at ${width}px`,async({page})=>{
  test.setTimeout(90000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width,height:960});
  await page.goto(pathToFileURL(path.resolve('public/client.html')).href);
  await page.waitForFunction(()=>assetsReady);
  await page.locator('#profileCompanyName').fill('Carrier UI');
  await page.locator('#profileOnboardingConfirm').click();
  await page.evaluate(()=>{
    Economy.creditActivity({id:'carrier-ui',matchId:'carrier-ui',money:0,supplies:0,inventory:{Medea:1,WhiteBase:1,Type61:4}});
    Economy.receiveDeliveries();
    const state=Economy.snapshot(),storage=state.storage,items=[...storage.units,...storage.ships];
    const hull=items.find(i=>i.unitId==='Medea'),ship=items.find(i=>i.unitId==='WhiteBase'),cargo=items.filter(i=>i.unitId==='Type61');
    const entry=i=>({unitId:i.unitId,kitId:i.kitId,stockId:i.id});
    const units=[entry(hull),...cargo.slice(0,2).map(i=>({...entry(i),preload:{carrierIndex:0,hangarId:'Hangar_1'}})),entry(ship)];
    cargo[0].rentalUses=3;cargo[2].rentalUses=4;
    cargo[1].contactLoan='anaheim-8';cargo[3].contactLoan='anaheim-8';
    state.contactTasks.push({id:'anaheim-8',status:'accepted',progress:0,loanTracking:true});
    localStorage.setItem('projectgreed.economy.v1',SaveCodec.stringify(state));
    localStorage.setItem('slg-formations-v1.PMC',JSON.stringify({version:3,squads:[{name:'Cargo',units}]}));
  });
  await page.reload();await page.waitForFunction(()=>assetsReady);
  await page.locator('#shellHangar').click();
  await page.locator('#shellFormation').click();
  const group=page.locator('[data-fleet-carrier="0"]');
  await expect(group.locator('[data-cargo-index]')).toHaveCount(2);
  await expect(group.locator('[data-cargo-index="1"] .catalog-rental-badge')).toHaveText('租赁 3');
  await expect(group.locator('[data-cargo-index="2"] .formation-task-badge')).toHaveText('任务');
  await expect(group.locator('.formation-row')).toHaveCount(1);
  await expect(page.locator('.formation-hangar-card')).toHaveCount(0);
  await expect(page.locator('[data-fleet-carrier="3"] .formation-cargo-empty-slot').first()).toBeVisible();
  const remaining=await page.evaluate(()=>Rules.formationModel(Formation.current()[0]).hangars.reduce((sum,h)=>sum+h.capacity,0)-2);
  await expect(group.locator('.formation-cargo-empty-slot')).toHaveCount(remaining);
  const firstHull=await group.boundingBox(),secondHull=await page.locator('[data-fleet-carrier="3"]').boundingBox();
  expect(secondHull.y).toBeGreaterThanOrEqual(firstHull.y+firstHull.height);
  expect(Math.abs(secondHull.x-firstHull.x)).toBeLessThan(2);
  const listWidth=await page.locator('#formationUnits').evaluate(list=>list.clientWidth);
  expect(firstHull.width).toBeGreaterThan(listWidth-40);
  const total=await page.evaluate(()=>Formation.current().slice(0,3).reduce((sum,e)=>sum+Rules.formationModel(e).cost+PilotSystem.cost(e.customPilot),0));
  await expect(group.locator('.formation-carrier-total')).toHaveText('总 COST '+total);
  expect(await group.locator('[data-manage-cargo]').evaluate(button=>button.scrollWidth<=button.clientWidth)).toBe(true);
  expect(await group.locator('.formation-cargo-pilot').evaluateAll(images=>images.every(i=>i.complete&&i.naturalWidth>0))).toBe(true);
  const row=await group.locator('.formation-row').boundingBox(),strip=await group.locator('.formation-cargo-portraits').boundingBox();
  expect(strip.y).toBeGreaterThanOrEqual(row.y+row.height);
  expect(strip.x+strip.width).toBeLessThanOrEqual(width);
  await page.screenshot({path:`tmp/verification/screenshots/formation-carrier-summary-${width}.png`});
  await group.locator('[data-cargo-index="2"]').click();
  await expect(page.locator('#formationCargoBack')).toBeVisible();
  await expect(group.locator('[data-formation-index="2"]')).toBeFocused();
  await expect(group.locator('[data-formation-index="2"]')).toHaveClass(/formation-cargo-located/);
  await expect(group.locator('.formation-preloaded-row')).toHaveCount(2);
  await expect(group.locator('.formation-preloaded-row .catalog-pilot-badge')).toHaveCount(2);
  await expect(group.locator('[data-formation-index="1"] .catalog-rental-badge')).toHaveText('租赁 3');
  await expect(group.locator('[data-formation-index="2"] .formation-task-badge')).toHaveText('任务');
  expect(await group.locator('.catalog-pilot-badge img').evaluateAll(images=>images.every(i=>i.complete&&i.naturalWidth>0))).toBe(true);
  for(const badge of await group.locator('.formation-preloaded-row .catalog-pilot-badge').all()){
    const b=await badge.boundingBox(),frame=await badge.locator('..').boundingBox();
    expect(b.x).toBeGreaterThanOrEqual(frame.x);expect(b.y).toBeGreaterThanOrEqual(frame.y);
    expect(b.x+b.width).toBeLessThanOrEqual(frame.x+frame.width+1);expect(b.y+b.height).toBeLessThanOrEqual(frame.y+frame.height+1);
  }
  await group.locator('[data-formation-index="1"]').getByRole('button',{name:'移除',exact:true}).click();
  await expect(group.locator('.formation-preloaded-row')).toHaveCount(1);
  await page.locator('#formationCargoBack').click();
  await expect(group.locator('.formation-cargo-empty-slot')).toHaveCount(remaining+1);
  await group.locator('.formation-cargo-empty-slot').first().click();
  await expect(page.locator('#formationUnitPicker')).toBeVisible();
  await expect(page.locator('#formationCargoBack')).toBeVisible();
  await expect(page.locator('#formationCatalog .catalog-pilot-badge').first()).toBeVisible();
  await expect(page.locator('#formationCatalog .catalog-rental-badge').filter({hasText:'租赁 4'})).toBeVisible();
  await expect(page.locator('#formationCatalog .formation-task-badge').first()).toBeVisible();
  await page.locator('[data-unit-id="Type61"] strong').first().click();
  await page.locator('#addFormationUnit').click();
  expect(await page.evaluate(()=>Formation.current().at(-1).preload)).toEqual({carrierIndex:0,hangarId:'Hangar_1'});
  await page.locator('#closeFormationPicker').click();
  await expect(page.locator('#formationCargoBack')).toBeVisible();
  await page.locator('#formationCargoBack').click();
  await expect(group.locator('[data-cargo-index]')).toHaveCount(2);
  await page.reload();await page.waitForFunction(()=>assetsReady);await page.locator('#shellHangar').click();await page.locator('#shellFormation').click();
  await expect(group.locator('[data-cargo-index]')).toHaveCount(2);
  await page.locator('#formationEditorStyle').selectOption('free');
  await expect(group.locator('[data-cargo-index]')).toHaveCount(2);
  await page.locator('#formationEditorStyle').selectOption('standard');
  await group.getByRole('button',{name:'移除',exact:true}).click();
  await expect(page.locator('.formation-unassigned')).toContainText('61式');
  expect(errors).toEqual([]);
});

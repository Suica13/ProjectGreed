const {test,expect}=require("@playwright/test");
const {pathToFileURL}=require("node:url"),path=require("node:path");
const url=pathToFileURL(path.resolve("public/client.html")).href;
test("MEGA uses native three-part sheets at ten by three cells; remote bursts retain trails",async({page})=>{
 const errors=[];page.on("pageerror",error=>errors.push(error.message));
 await page.goto(url);await page.waitForFunction(()=>assetsReady);
 const result=await page.evaluate(async()=>{
  Net.leave();
  const unit={id:"zz",model:Object.keys(UnitModels).find(id=>UnitModels[id].prefabId==="MSZ_010"),x:2,y:3,hp:100000,en:100000};
  const remote={id:"remote",model:Object.keys(UnitModels).find(id=>UnitModels[id].prefabId==="MSN_02"),x:2,y:3,hp:100000,en:100000};
  await SpriteRenderer.ensureAssets(SpriteRenderer.battleKeys({units:[unit,remote]}));
  const canvas=document.createElement("canvas");canvas.width=900;canvas.height=500;canvas.id="mega-effect-evidence";
  Object.assign(canvas.style,{position:"fixed",inset:0,zIndex:999999,width:"900px",height:"500px",background:"#101824"});document.body.append(canvas);
  const ctx=canvas.getContext("2d"),draw=ctx.drawImage.bind(ctx),calls=[];
  ctx.drawImage=(image,...args)=>{calls.push({key:Object.keys(SpriteRenderer.images).find(key=>SpriteRenderer.images[key]===image),args});draw(image,...args);};
  const skill=Rules.unitSkills(unit).find(s=>s.type==="irradiation");
  IrradiationFX.reset();IrradiationFX.start({id:"mega-check",unitId:unit.id,model:unit.model,from:{x:1,y:4},to:{x:11,y:4},color:skill.visualColor,areaWidth:3,beamWidth:skill.beamWidth,beamSections:skill.beamSections,beamLength:skill.beamLength,chargeSeconds:.2,fireSeconds:2,chargeScale:skill.chargeScale,hits:[]});
  const position=(x,y)=>({x:x*40,y:y*40});
  IrradiationFX.draw(ctx,0,position,40);calls.length=0;IrradiationFX.draw(ctx,700,position,40);
  const beam=calls.filter(c=>c.key?.includes("Irradiation_")).map(c=>({key:c.key,left:c.args[4],width:c.args[6],height:c.args[7]}));
  IrradiationFX.reset();
  const weapon=UnitModels[remote.model].weapons.find(w=>w.remote);
  const target={id:"target",model:"Type61__standard",hp:100000,x:7,y:3};
  const source={unit:remote,x:80,y:370,angle:90,scale:1};
  const to={unit:target,x:420,y:370,angle:270,scale:1};
  const plan=WeaponEffects.plan(weapon,source,to,{id:"native-burst",hit:true});
  calls.length=0;WeaponEffects.draw(ctx,weapon,plan,.85,source,{hit:true},1);
  const trailDraws=calls.filter(c=>c.key?.includes("remote-trail")).length;
  const origins=plan.shots.filter(s=>s.remoteIndex===0).map(s=>s.origin);
  const finite=plan.shots.every(s=>Number.isFinite(s.origin.x)&&Number.isFinite(s.origin.y)&&Number.isFinite(s.impactAt));
  const opacity=ctx.getImageData(0,0,900,500).data.some((value,index)=>index%4===3&&value>0);
  return {beam,trailDraws,shots:plan.shots.length,origins,finite,opacity};
 });
 expect(result.beam).toHaveLength(3);expect(result.beam.every(part=>part.height===120)).toBe(true);
 expect(Math.max(...result.beam.map(part=>part.left+part.width))).toBeCloseTo(400,4);
 expect(result.shots).toBe(20);expect(result.trailDraws).toBeGreaterThan(0);
 expect(result.finite).toBe(true);expect(result.opacity).toBe(true);
 expect(result.origins.slice(0,5).every(point=>point.x===result.origins[0].x&&point.y===result.origins[0].y)).toBe(true);
 expect(result.origins[5]).not.toEqual(result.origins[0]);
 await page.locator("#mega-effect-evidence").screenshot({path:"build/mega-remote-effects.png"});
 expect(errors).toEqual([]);
});

 await expect(dialogue.locator('p')).toHaveText(expected);
 if(language==='en')expect(await dialogue.locator('p').textContent()).not.toMatch(/[\u3400-\u9fff]/);
 await page.screenshot({path:`tmp/verification/screenshots/v126-mission-${language}.png`});
 for(let n=0;n<3;n++)await dialogue.locator('button').click();await expect(dialogue).toBeHidden();
 await page.locator('#missionObjectives').click();await expect(page.locator('#missionObjectivesTitle')).toHaveText(language==='en'?'Mission Objectives':'任務目標');
